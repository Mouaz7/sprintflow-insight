import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import MessageFormat from '@messageformat/core';
import compileModule from '@messageformat/core/compile-module.js';

const source = new URL('../src/shared/i18n/icu.messages.json', import.meta.url);
const target = new URL('../src/shared/i18n/icu.generated.ts', import.meta.url);
const messages = JSON.parse(readFileSync(source, 'utf8')) as Record<
  'EN' | 'SV',
  Record<string, string>
>;
const englishKeys = Object.keys(messages.EN).sort().join(',');
if (Object.keys(messages.SV).sort().join(',') !== englishKeys)
  throw new Error('Every ICU message must have both EN and SV translations.');
const compiler = new MessageFormat(['en-GB', 'sv-SE'], {
  localeCodeFromKey: (key: string) =>
    (({ EN: 'en-GB', SV: 'sv-SE' }) as Record<string, string>)[key] ?? null,
});
const output =
  '// Generated by npm run messages:compile from icu.messages.json. Do not edit.\n' +
  `import type { CompiledMessages } from './icu.types';\n` +
  `const plural = (...args: Parameters<typeof runtimePlural>): string => String(runtimePlural(...args));\n` +
  compileModule(compiler, messages)
    .replace(
      /import \{([^}]+)\} from "@messageformat\/runtime";/,
      (_match: string, imports: string) =>
        `import {${imports.replace(/\bplural\b/, 'plural as runtimePlural')}} from "@messageformat/runtime";`,
    )
    .replace(
      'export default ',
      'const messages: { EN: CompiledMessages; SV: CompiledMessages } = ',
    )
    .replaceAll('function(value)', 'function(value: Date | number)')
    .replace(/var opt = (\{[^\n]+\});/g, 'const opt = $1 as const;') +
  ';\nexport default messages;\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw new Error(
      `ICU messages are stale: run npm run messages:compile (${fileURLToPath(target)}).`,
    );
} else writeFileSync(target, output);
