-- B7: planning poker. One session estimates one story in rounds; votes stay hidden until the
-- facilitator reveals the round. A revote starts a new round and keeps earlier rounds as history.

CREATE TABLE poker_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  story_id BIGINT NOT NULL,
  -- The account that started the session; it may reveal, revote, accept and cancel.
  facilitator_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  deck VARCHAR(16) NOT NULL,
  -- JSON array of the playable cards in deck order (PokerDeck); fixed for the session.
  cards VARCHAR(1000) NOT NULL,
  status VARCHAR(16) NOT NULL,
  round INTEGER NOT NULL DEFAULT 1,
  -- The last round whose votes were revealed (0: none). Votes of later rounds never leave the
  -- server; a round closed unrevealed has its votes deleted.
  revealed_round INTEGER NOT NULL DEFAULT 0,
  final_value VARCHAR(8),
  final_story_points INTEGER,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  closed_at TIMESTAMP WITH TIME ZONE,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT poker_story_project_fk FOREIGN KEY (story_id, project_id)
    REFERENCES user_stories(id, project_id) ON DELETE CASCADE,
  CONSTRAINT poker_session_deck_known CHECK (deck IN ('FIBONACCI', 'TSHIRT', 'CUSTOM')),
  CONSTRAINT poker_session_status_known
    CHECK (status IN ('VOTING', 'REVEALED', 'ACCEPTED', 'CANCELLED')),
  CONSTRAINT poker_session_round_positive CHECK (round BETWEEN 1 AND 50),
  CONSTRAINT poker_session_revealed_round CHECK (revealed_round IN (round - 1, round)),
  CONSTRAINT poker_session_final_points_allowed
    CHECK (final_story_points IS NULL OR final_story_points IN (1, 2, 3, 5, 8)),
  CONSTRAINT poker_session_accepted_has_result
    CHECK ((status = 'ACCEPTED') = (final_story_points IS NOT NULL))
);

-- At most one open session per story; concurrent starts lose on this index (409).
CREATE UNIQUE INDEX poker_session_one_open_per_story
  ON poker_session(story_id) WHERE status IN ('VOTING', 'REVEALED');
CREATE INDEX poker_session_project_idx ON poker_session(project_id, status);

CREATE TABLE poker_vote (
  session_id BIGINT NOT NULL REFERENCES poker_session(id) ON DELETE CASCADE,
  round INTEGER NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  card VARCHAR(8) NOT NULL,
  voted_at TIMESTAMP WITH TIME ZONE NOT NULL,
  PRIMARY KEY (session_id, round, user_id)
);
