CREATE TABLE user_preferences (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 language VARCHAR(2) NOT NULL DEFAULT 'EN', theme VARCHAR(8) NOT NULL DEFAULT 'light',
 notifications BOOLEAN NOT NULL DEFAULT TRUE, onboarding_completed BOOLEAN NOT NULL DEFAULT FALSE,
 saved_filters TEXT NOT NULL DEFAULT '[]', version BIGINT
);
CREATE TABLE retrospective_entry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL,
 sprint_id BIGINT NOT NULL, author_email VARCHAR(255) NOT NULL, category VARCHAR(20) NOT NULL,
 message VARCHAR(1000) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL, version BIGINT
);
CREATE INDEX retrospective_project_sprint_idx ON retrospective_entry(project_id, sprint_id);
CREATE TABLE shared_report (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL,
 token_hash VARCHAR(64) NOT NULL UNIQUE, snapshot TEXT NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(255) NOT NULL
);
CREATE INDEX shared_report_project_idx ON shared_report(project_id);
CREATE INDEX shared_report_expiry_idx ON shared_report(expires_at);
