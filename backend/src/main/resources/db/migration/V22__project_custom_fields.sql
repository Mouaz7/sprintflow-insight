-- B16: typed project fields and task values. Project membership ids are public,
-- stable while membership exists, and cannot reattach to a newly joined account.
ALTER TABLE task ADD COLUMN custom_fields_revision BIGINT NOT NULL DEFAULT 0;
ALTER TABLE project_member ADD CONSTRAINT member_identity_project UNIQUE (id, project_id);

CREATE TABLE custom_field (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name VARCHAR(80) NOT NULL CHECK (length(btrim(name)) > 0),
  kind VARCHAR(10) NOT NULL CHECK (kind IN ('TEXT','NUMBER','DATE','SELECT','USER')),
  options JSONB NOT NULL DEFAULT '[]'::jsonb,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT custom_field_identity_project_kind UNIQUE (id, project_id, kind),
  CONSTRAINT custom_field_options CHECK (
    CASE WHEN jsonb_typeof(options) = 'array' THEN
      jsonb_array_length(options) <= 30
      AND CASE WHEN kind = 'SELECT' THEN jsonb_array_length(options) > 0 ELSE options = '[]'::jsonb END
    ELSE FALSE END)
);
CREATE UNIQUE INDEX custom_field_project_name ON custom_field(project_id, lower(name));

CREATE TABLE task_custom_value (
  task_id BIGINT NOT NULL,
  field_id BIGINT NOT NULL,
  project_id BIGINT NOT NULL,
  kind VARCHAR(10) NOT NULL,
  text_value VARCHAR(2000),
  number_value NUMERIC(24,6),
  date_value DATE,
  member_id BIGINT,
  CONSTRAINT custom_value_number_finite CHECK (
    number_value IS NULL OR number_value BETWEEN
      -999999999999999999.999999 AND 999999999999999999.999999),
  CONSTRAINT custom_value_date_range CHECK (
    date_value IS NULL OR date_value BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
  PRIMARY KEY (task_id, field_id),
  CONSTRAINT custom_value_task_project FOREIGN KEY (task_id, project_id)
    REFERENCES task(id, project_id) ON DELETE CASCADE,
  CONSTRAINT custom_value_field_project_kind FOREIGN KEY (field_id, project_id, kind)
    REFERENCES custom_field(id, project_id, kind) ON DELETE CASCADE,
  CONSTRAINT custom_value_member_project FOREIGN KEY (member_id, project_id)
    REFERENCES project_member(id, project_id) ON DELETE CASCADE,
  CONSTRAINT custom_value_typed CHECK (
    CASE kind
      WHEN 'TEXT' THEN text_value IS NOT NULL AND length(text_value) > 0 AND number_value IS NULL AND date_value IS NULL AND member_id IS NULL
      WHEN 'SELECT' THEN text_value IS NOT NULL AND length(text_value) > 0 AND number_value IS NULL AND date_value IS NULL AND member_id IS NULL
      WHEN 'NUMBER' THEN text_value IS NULL AND number_value IS NOT NULL AND date_value IS NULL AND member_id IS NULL
      WHEN 'DATE' THEN text_value IS NULL AND number_value IS NULL AND date_value IS NOT NULL AND member_id IS NULL
      WHEN 'USER' THEN text_value IS NULL AND number_value IS NULL AND date_value IS NULL AND member_id IS NOT NULL
      ELSE FALSE
    END)
);
-- Equality scope first, then typed range. These also cover field deletion cascades.
CREATE INDEX custom_value_project_field_task ON task_custom_value(project_id, field_id, task_id);
CREATE INDEX custom_value_field_fk ON task_custom_value(field_id, project_id, kind);
CREATE INDEX custom_value_number ON task_custom_value(project_id, field_id, number_value, task_id)
  WHERE number_value IS NOT NULL;
CREATE INDEX custom_value_date ON task_custom_value(project_id, field_id, date_value, task_id)
  WHERE date_value IS NOT NULL;
CREATE INDEX custom_value_member_fk ON task_custom_value(member_id, project_id)
  WHERE member_id IS NOT NULL;
