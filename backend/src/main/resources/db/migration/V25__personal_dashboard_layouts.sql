-- B18: one private layout for each project/account; reading defaults creates no row.
CREATE TABLE dashboard_layout (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 version BIGINT NOT NULL DEFAULT 0,
 widgets JSONB NOT NULL,
 CONSTRAINT dashboard_layout_project_user_unique UNIQUE(project_id,user_id),
 CONSTRAINT dashboard_layout_widgets_array CHECK(jsonb_typeof(widgets) = 'array' AND jsonb_array_length(widgets) <= 6)
);
CREATE INDEX dashboard_layout_user_idx ON dashboard_layout(user_id);
