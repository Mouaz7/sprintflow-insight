-- B3: epics, task dependencies and three-point (PERT) estimates.

-- 1. Epics -------------------------------------------------------------------------------------
CREATE TABLE epic (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  title VARCHAR(120) NOT NULL CHECK (btrim(title) <> ''),
  description VARCHAR(2000),
  color VARCHAR(7) NOT NULL DEFAULT '#4f46e5' CHECK (color ~ '^#[0-9a-f]{6}$'),
  start_date DATE,
  target_date DATE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT epic_dates_ordered CHECK (start_date IS NULL OR target_date IS NULL OR start_date <= target_date),
  CONSTRAINT epic_identity_project UNIQUE (id, project_id)
);
CREATE INDEX epic_project_idx ON epic(project_id);

-- A story belongs to at most one epic of its own project. Deleting the epic keeps the stories and
-- only clears the reference (PostgreSQL 15+ column list on SET NULL keeps project_id intact).
ALTER TABLE user_stories ADD COLUMN epic_id BIGINT;
ALTER TABLE user_stories ADD CONSTRAINT story_epic_project_fk
  FOREIGN KEY (epic_id, project_id) REFERENCES epic(id, project_id) ON DELETE SET NULL (epic_id);
CREATE INDEX story_epic_idx ON user_stories(epic_id) WHERE epic_id IS NOT NULL;

-- 2. Task dependencies ---------------------------------------------------------------------------
-- "blocker_task_id must be finished before blocked_task_id can finish". Both ends live in the same
-- project (composite foreign keys); cycles are rejected by the application under the project lock.
ALTER TABLE task ADD CONSTRAINT task_identity_project UNIQUE (id, project_id);

CREATE TABLE task_dependency (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  blocker_task_id BIGINT NOT NULL,
  blocked_task_id BIGINT NOT NULL,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT task_dependency_not_self CHECK (blocker_task_id <> blocked_task_id),
  CONSTRAINT task_dependency_unique UNIQUE (blocker_task_id, blocked_task_id),
  CONSTRAINT task_dependency_blocker_fk FOREIGN KEY (blocker_task_id, project_id)
    REFERENCES task(id, project_id) ON DELETE CASCADE,
  CONSTRAINT task_dependency_blocked_fk FOREIGN KEY (blocked_task_id, project_id)
    REFERENCES task(id, project_id) ON DELETE CASCADE
);
CREATE INDEX task_dependency_project_idx ON task_dependency(project_id);
CREATE INDEX task_dependency_blocked_idx ON task_dependency(blocked_task_id);

-- 3. Three-point estimates in working days -------------------------------------------------------
CREATE TABLE task_estimate (
  task_id BIGINT PRIMARY KEY,
  project_id BIGINT NOT NULL,
  optimistic_days NUMERIC(6, 2) NOT NULL,
  most_likely_days NUMERIC(6, 2) NOT NULL,
  pessimistic_days NUMERIC(6, 2) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT task_estimate_ordered CHECK (
    optimistic_days >= 0 AND optimistic_days <= most_likely_days
    AND most_likely_days <= pessimistic_days AND pessimistic_days <= 1000),
  CONSTRAINT task_estimate_task_fk FOREIGN KEY (task_id, project_id)
    REFERENCES task(id, project_id) ON DELETE CASCADE
);
CREATE INDEX task_estimate_project_idx ON task_estimate(project_id);
