-- B4: time tracking per task and member capacity per sprint.

-- Estimate in minutes. NULL means "not estimated", which differs from an explicit zero.
ALTER TABLE task ADD COLUMN estimate_minutes INTEGER;
ALTER TABLE task ADD CONSTRAINT task_estimate_range
  CHECK (estimate_minutes IS NULL OR estimate_minutes BETWEEN 0 AND 600000);

-- One row per logged period. A running timer has started_at and no minutes yet; stopping it fills
-- in minutes. A manual entry has minutes and no started_at. Tasks never move between projects, so
-- project_id stays consistent with the task and keeps project-scoped queries index-only.
-- user_id becomes NULL when the account is deleted: the project keeps its actual hours, but they
-- no longer point at a person (running timers are removed first, see WorkspaceAccountListener).
CREATE TABLE time_entry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  task_id BIGINT NOT NULL,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  spent_on DATE NOT NULL,
  minutes INTEGER,
  started_at TIMESTAMP WITH TIME ZONE,
  note VARCHAR(500),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT time_entry_task_project_fk FOREIGN KEY (task_id, project_id)
    REFERENCES task(id, project_id) ON DELETE CASCADE,
  CONSTRAINT time_entry_minutes_range CHECK (minutes IS NULL OR minutes BETWEEN 1 AND 1440),
  CONSTRAINT time_entry_running_or_logged CHECK (minutes IS NOT NULL OR started_at IS NOT NULL),
  CONSTRAINT time_entry_running_has_user CHECK (minutes IS NOT NULL OR user_id IS NOT NULL)
);
-- At most one running timer per account, across all projects. Concurrent starts race on this index.
CREATE UNIQUE INDEX time_entry_one_running_timer ON time_entry(user_id) WHERE minutes IS NULL;
CREATE INDEX time_entry_task_idx ON time_entry(task_id, id);
CREATE INDEX time_entry_project_idx ON time_entry(project_id, id);

-- Member capacity for one sprint. Working days come from the sprint dates (Monday to Friday);
-- days off are weekdays inside the sprint that the member is away. point_capacity is the member's
-- story points for a full sprint at 100 % availability; NULL when the team plans in hours only.
CREATE TABLE sprint_capacity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  sprint_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  minutes_per_day INTEGER NOT NULL,
  availability_percent INTEGER NOT NULL,
  point_capacity INTEGER,
  days_off DATE[] NOT NULL DEFAULT '{}',
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT sprint_capacity_sprint_fk FOREIGN KEY (sprint_id, project_id)
    REFERENCES sprint(id, project_id) ON DELETE CASCADE,
  CONSTRAINT sprint_capacity_sprint_user_unique UNIQUE (sprint_id, user_id),
  CONSTRAINT sprint_capacity_minutes_range CHECK (minutes_per_day BETWEEN 0 AND 1440),
  CONSTRAINT sprint_capacity_availability_range CHECK (availability_percent BETWEEN 0 AND 100),
  CONSTRAINT sprint_capacity_points_range CHECK (point_capacity IS NULL OR point_capacity BETWEEN 0 AND 10000),
  CONSTRAINT sprint_capacity_days_off_limit CHECK (cardinality(days_off) <= 366)
);
CREATE INDEX sprint_capacity_user_idx ON sprint_capacity(user_id);
